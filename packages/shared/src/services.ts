/** One of the 39 resource types. */
export type ServiceId = (typeof SERVICES)[number]["id"];

export const SERVICE_IDS = SERVICES.map((service) => service.id) as readonly ServiceId[];

const byId = new Map<string, ServiceDefinition>(SERVICES.map((service) => [service.id, service]));

export function isServiceId(value: string): value is ServiceId {
  return byId.has(value);
}

/** The catalog entry for a service id, or `undefined` if there is none. */
export function findService(id: string): ServiceDefinition | undefined {
  return byId.get(id);
}
