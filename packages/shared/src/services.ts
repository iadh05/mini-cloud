/**
 * The service catalog: every service Mini Cloud offers, in one place.
 * The `services` table is synced from this list on every migration, and
 * `resources.type` must be one of these ids.
 * Design of each service: docs/services/<path>.md
 */

export const SERVICE_CATEGORIES = [
  "compute",
  "networking",
  "storage",
  "databases",
  "security",
  "observability",
  "integration",
  "delivery",
  "billing",
] as const;
export type ServiceCategory = (typeof SERVICE_CATEGORIES)[number];

/** `planned` → being designed; `beta` → being built, usable for testing; `available` → done. */
export const SERVICE_STATUSES = ["planned", "beta", "available"] as const;
export type ServiceStatus = (typeof SERVICE_STATUSES)[number];

export interface ServiceDefinition {
  /** Resource type stored in `resources.type`, singular kebab-case. */
  readonly id: string;
  /** Position in the catalog (1–39). */
  readonly number: number;
  readonly name: string;
  readonly category: ServiceCategory;
  /** API path segment: `/v1/<path>`, plural kebab-case. */
  readonly path: string;
  /** What it is called on AWS. */
  readonly aws: string;
  /** What runs it under the hood. */
  readonly engine: string;
  /** Roadmap phase in which it is first delivered. */
  readonly phase: number;
  readonly status: ServiceStatus;
}

